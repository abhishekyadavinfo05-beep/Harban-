-- Public read only for active product variants & images
drop policy if exists "Public read active variants" on public.product_variants;
create policy "Public read active variants"
  on public.product_variants for select
  using (
    public.is_admin()
    or (
      is_active = true
      and exists (
        select 1 from public.products p
        where p.id = product_variants.product_id and p.is_active = true
      )
    )
  );

drop policy if exists "Admins manage variants" on public.product_variants;
create policy "Admins manage variants"
  on public.product_variants for all
  using (public.is_admin())
  with check (public.is_admin());

drop policy if exists "Public read active product images" on public.product_images;
create policy "Public read active product images"
  on public.product_images for select
  using (
    public.is_admin()
    or exists (
      select 1 from public.products p
      where p.id = product_images.product_id and p.is_active = true
    )
  );

drop policy if exists "Admins manage product images" on public.product_images;
create policy "Admins manage product images"
  on public.product_images for all
  using (public.is_admin())
  with check (public.is_admin());

-- Customers read their own fulfillments; only admins write
drop policy if exists "Fulfillments read own or admin" on public.fulfillments;
create policy "Fulfillments read own or admin"
  on public.fulfillments for select
  using (
    public.is_admin()
    or exists (
      select 1 from public.orders o
      where o.order_code = fulfillments.order_code
        and public.is_owner_uid_or_email(o.customer_uid, o.customer_email)
    )
  );

drop policy if exists "Fulfillments admin write" on public.fulfillments;
create policy "Fulfillments admin write"
  on public.fulfillments for all
  using (public.is_admin())
  with check (public.is_admin());

